// Trả về thẻ <svg> hoàn chỉnh cho 1 icon (stroke = currentColor của
// thẻ cha; size = px; strokeWidth mặc định 2).
export function iconSvg(name, size, strokeWidth) {
  const inner = ICON_PATHS[name];
  if (!inner) return '';
  const s = size || 20;
  const w = strokeWidth || 2;
  return '<svg viewBox="0 0 24 24" width="' + s + '" height="' + s
    + '" fill="none" stroke="currentColor" stroke-width="' + w
    + '" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + inner + '</svg>';
}
